// Builds src/lib/voice-manifest.ts from scripts/voice-clips.txt (key time job-id per line).
// Each clip is a pre-recorded human voice line (short, trimmed MP3). Run: node scripts/make-voice-manifest.mjs
import { readFileSync, writeFileSync } from "node:fs";

const BASE = "https://d8j0ntlcm91z4.cloudfront.net/user_2zkin0wWd1fqvOlkf1ZVTn9Up98";
const rows = readFileSync(new URL("./voice-clips.txt", import.meta.url), "utf8")
  .split("\n")
  .map((l) => l.trim())
  .filter(Boolean)
  .map((l) => l.split(/\s+/));

const body = rows
  .map(([key, time, id]) => `  ${JSON.stringify(key)}: "${BASE}/hf_${time.includes("_") ? time : "20261017_" + time}_${id}.mp3",`)
  .join("\n");

writeFileSync(
  new URL("../src/lib/voice-manifest.ts", import.meta.url),
  `// GENERATED by scripts/make-voice-manifest.mjs - do not edit by hand.
// Where each pre-recorded voice clip lives. If the clips are ever copied into public/voice/
// (one <key>.mp3 per clip), flip VOICE_LOCAL to true and the game will use those files instead.
export const VOICE_LOCAL = false;

export const VOICE_URLS: Record<string, string> = {
${body}
};
`,
);
console.log("wrote " + rows.length + " clips");
